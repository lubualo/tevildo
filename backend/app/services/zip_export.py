"""
ZIP export service.

Creates ZIP archives with invoice PDFs grouped by month.
"""
import zipfile
from datetime import date, timedelta
from io import BytesIO
from pathlib import Path
from typing import List

from app.models.invoice import Invoice
from app.models.stored_file import StoredFile
from app.models.settings import UserSettings
from app.services.excel_report import ExcelReportGenerator
from app.settings import settings as app_settings


class ZipExportGenerator:
    """Generates ZIP archives with invoice PDFs and reports."""

    def __init__(
        self,
        invoices: List[Invoice],
        stored_files: dict,  # {invoice_id: StoredFile}
        user_settings: UserSettings,
        date_from: date,
        date_to: date,
        category_info: dict = None,
        include_excel: bool = True,
    ):
        self.invoices = invoices
        self.stored_files = stored_files
        self.user_settings = user_settings
        self.date_from = date_from
        self.date_to = date_to
        self.category_info = category_info
        self.include_excel = include_excel

    def generate(self) -> BytesIO:
        """Generate ZIP archive with PDFs grouped by month."""
        output = BytesIO()

        with zipfile.ZipFile(output, 'w', zipfile.ZIP_DEFLATED) as zf:
            # Group invoices by month
            invoices_by_month = {}
            for inv in self.invoices:
                if inv.issue_date:
                    year_month = inv.issue_date[:7]  # "YYYY-MM"
                    if year_month not in invoices_by_month:
                        invoices_by_month[year_month] = []
                    invoices_by_month[year_month].append(inv)

            # Add PDFs to ZIP, organized by month folders
            for year_month, month_invoices in sorted(invoices_by_month.items()):
                # Create folder name like "2025-01"
                folder = year_month

                for inv in month_invoices:
                    stored_file = self.stored_files.get(inv.id)
                    if not stored_file:
                        continue

                    # Get physical file path
                    file_path = app_settings.tevildo_data_dir / stored_file.relative_path
                    if not file_path.exists():
                        continue

                    # Create meaningful filename
                    # Format: YYYY-MM-DD_InvoiceNumber_Client.pdf
                    invoice_num = (inv.invoice_number or "unknown").replace("/", "-")
                    client = (inv.client_name or "unknown")[:30].replace("/", "-").replace("\\", "-")
                    filename = f"{inv.issue_date}_{invoice_num}_{client}.pdf"

                    # Add to ZIP
                    arcname = f"{folder}/{filename}"
                    zf.write(file_path, arcname)

            # Add Excel report if requested
            if self.include_excel:
                excel_generator = ExcelReportGenerator(
                    invoices=self.invoices,
                    settings=self.user_settings,
                    date_from=self.date_from,
                    date_to=self.date_to,
                    category_info=self.category_info,
                )
                excel_data = excel_generator.generate()
                zf.writestr("report.xlsx", excel_data.getvalue())

            # Add a simple README
            readme_content = self._generate_readme()
            zf.writestr("README.txt", readme_content)

        output.seek(0)
        return output

    def _generate_readme(self) -> str:
        """Generate README content for the ZIP."""
        company = self.user_settings.company_name or "Tevildo Export"
        total_ars = sum(float(inv.total_ars or 0) for inv in self.invoices)

        return f"""Monotributo Invoice Export
==========================

Company: {company}
Period: {self.date_from.strftime('%d/%m/%Y')} - {self.date_to.strftime('%d/%m/%Y')}
Total Invoices: {len(self.invoices)}
Total Amount (ARS): ${total_ars:,.2f}

Contents:
- PDFs organized by month (YYYY-MM folders)
- report.xlsx - Detailed Excel report

Generated by Tevildo
"""
